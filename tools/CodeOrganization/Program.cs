using System.Text.Json;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

var root = Path.GetFullPath(args.ElementAtOrDefault(1) ?? ".");
var mode = args.ElementAtOrDefault(0) ?? "check";
try
{
    if (mode == "verify-preservation")
    {
        return PreservationVerifier.Run(root);
    }

    if (mode is not ("check" or "format"))
    {
        Console.Error.WriteLine("Usage: dotnet run --project tools/CodeOrganization -- [check|format|verify-preservation] [repository-root]");
        return 2;
    }

    var src = Path.GetFullPath(Path.Combine(root, "Backend/ElectronicRegisterAPI/src"));
    var generatedFiles = JsonSerializer.Deserialize<string[]>(File.ReadAllText(Path.Combine(root, "tools/CodeOrganization/generated-sources.json")))!.ToHashSet();
    var files = Directory.GetFiles(src, "*.cs", SearchOption.AllDirectories)
        .Where(p => !p.Split(Path.DirectorySeparatorChar).Any(s => s is "obj" or "bin")).Order().ToArray();
    var projects = Directory.GetFiles(src, "*.csproj", SearchOption.AllDirectories);
    var entries = new List<object>();
    var violations = new List<string>();
    var typeCount = 0;
    var allowed = new Dictionary<string, string[]>
    {
        ["Domain"] = [],
        ["Business"] = ["Domain"],
        ["Application"] = ["Domain", "Business"],
        ["Infrastructure"] = ["Domain"],
        ["Api"] = ["Domain", "Business", "Application", "Infrastructure"]
    };

    foreach (var file in files)
    {
        var relative = Path.GetRelativePath(root, file).Replace('\\', '/');
        var text = File.ReadAllText(file);
        var generated = generatedFiles.Contains(relative) || text.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
        var unit = CSharpSyntaxTree.ParseText(text).GetCompilationUnitRoot();
        if (mode == "format" && !generated)
        {
            text = SourceLayout.Format(unit);
            File.WriteAllText(file, text);
            unit = CSharpSyntaxTree.ParseText(text).GetCompilationUnitRoot();
        }

        var types = unit.DescendantNodes().Where(t => t is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax)
            .Where(t => t.Parent is BaseNamespaceDeclarationSyntax or CompilationUnitSyntax).ToArray();
        typeCount += types.Length;
        var ns = unit.DescendantNodes().OfType<BaseNamespaceDeclarationSyntax>().FirstOrDefault()?.Name.ToString() ?? "";
        var project = projects.Select(Path.GetDirectoryName).Where(d => file.StartsWith(d! + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase)).OrderByDescending(d => d!.Length).FirstOrDefault();
        var layer = relative.Split('/')[3];
        var expected = project is null ? "" : (layer == "Api" ? "ElectronicRegisterAPI.Api" : Path.GetFileName(project)) + "." + Path.GetRelativePath(project, Path.GetDirectoryName(file)!).Replace('\\', '.');
        var reason = generated ? "Database First scaffold allowlist or explicit auto-generated header; regeneration is authoritative" : "";
        foreach (var error in unit.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error))
        {
            violations.Add($"syntax: {relative}: {error}");
        }

        if (!generated)
        {
            if (types.Length > 1)
            {
                violations.Add($"multiple-types: {relative}: {string.Join(", ", types.Select(Name))}");
            }

            if (types.Length == 1 && Path.GetFileNameWithoutExtension(file) != Name(types[0]) && !(types[0] is BaseTypeDeclarationSyntax partial && partial.Modifiers.Any(SyntaxKind.PartialKeyword)))
            {
                violations.Add($"filename: {relative}: {Name(types[0])}");
            }

            if (types.Length > 0 && (ns != expected.TrimEnd('.') || unit.DescendantNodes().OfType<BaseNamespaceDeclarationSyntax>().Any(n => n.Name.ToString() != expected.TrimEnd('.'))))
            {
                violations.Add($"namespace: {relative}: {ns} expected {expected}");
            }

            foreach (var type in types)
            {
                var name = Name(type);
                if (type is EnumDeclarationSyntax && !relative.Contains("/Enums/")) violations.Add($"enum-location: {relative}: {name}");
                if (type is InterfaceDeclarationSyntax && !relative.Contains("/Interfaces/")) violations.Add($"interface-location: {relative}: {name}");
                if (name.EndsWith("Exception") && !relative.Contains("/Exceptions/")) violations.Add($"exception-location: {relative}: {name}");
                if (type is InterfaceDeclarationSyntax && name.EndsWith("Repository") && !relative.Contains("/Interfaces/Repositories/") && !relative.Contains("/Interfaces/Persistence/")) violations.Add($"repository-contract-location: {relative}: {name}");
                if (type is InterfaceDeclarationSyntax && name.EndsWith("Manager") && !relative.Contains("/Interfaces/Managers/") && name != "ITransactionManager") violations.Add($"manager-contract-location: {relative}: {name}");
            }

            foreach (var type in unit.DescendantNodes().OfType<BaseTypeDeclarationSyntax>().Where(t => t.Parent is TypeDeclarationSyntax && !t.Modifiers.Any(SyntaxKind.PrivateKeyword)))
            {
                violations.Add($"nested-type-review: {relative}: {type.Identifier.Text}");
            }

            foreach (var list in unit.DescendantNodes().OfType<ParameterListSyntax>().Where(p => p.Parameters.Count >= 4))
            {
                var lines = list.Parameters.Select(p => p.GetLocation().GetLineSpan().StartLinePosition.Line).ToArray();
                if (lines.Distinct().Count() != lines.Length) violations.Add($"compressed-parameters: {relative}: line {lines[0] + 1}");
            }

            foreach (var block in unit.DescendantNodes().OfType<BlockSyntax>())
            {
                var lines = block.Statements.Select(s => s.GetLocation().GetLineSpan().StartLinePosition.Line).ToArray();
                if (lines.Distinct().Count() != lines.Length) violations.Add($"compressed-statements: {relative}: line {lines.FirstOrDefault() + 1}");
            }

            foreach (var import in unit.DescendantNodes().OfType<UsingDirectiveSyntax>())
            {
                var imported = import.Name?.ToString() ?? "";
                foreach (var other in allowed.Keys.Where(l => l != layer && !allowed[layer].Contains(l)))
                {
                    var prefix = other == "Api" ? "ElectronicRegisterAPI.Api" : "ElectronicRegisterAPI." + other;
                    if (imported == prefix || imported.StartsWith(prefix + ".")) violations.Add($"source-dependency: {relative}: {imported}");
                }
            }
        }

        entries.Add(new
        {
            file = relative,
            layer,
            project = project is null ? null : Path.GetRelativePath(root, project).Replace('\\', '/'),
            generated,
            exclusionReason = reason,
            @namespace = ns,
            classification = project is null ? "Empty orphan source (not compiled)" : Path.GetRelativePath(project, Path.GetDirectoryName(file)!).Replace('\\', '/'),
            types = types.Select(t => new
            {
                name = Name(t),
                kind = t.Kind().ToString(),
                nestedTypes = t.DescendantNodes().OfType<BaseTypeDeclarationSyntax>().Select(n => new { name = n.Identifier.Text, visibility = n.Modifiers.ToFullString() })
            })
        });
    }

    var graph = new Dictionary<string, string[]>();
    var dependencies = projects.Select(p =>
    {
        var layer = Path.GetRelativePath(src, p).Split(Path.DirectorySeparatorChar)[0];
        var references = XDocument.Load(p).Descendants("ProjectReference").Select(x => Path.GetFullPath(Path.Combine(Path.GetDirectoryName(p)!, ((string)x.Attribute("Include")!).Replace('\\', Path.DirectorySeparatorChar)))).ToArray();
        var targets = references.Select(r => Path.GetRelativePath(src, r).Split(Path.DirectorySeparatorChar)[0]).ToArray();
        foreach (var target in targets)
        {
            if (!allowed[layer].Contains(target)) violations.Add($"dependency: {layer}: {target}");
        }

        graph[layer] = targets;
        return new { project = Path.GetRelativePath(root, p).Replace('\\', '/'), layer, references = references.Select(r => Path.GetRelativePath(root, r).Replace('\\', '/')) };
    }).ToArray();
    foreach (var layer in graph.Keys)
    {
        DetectCycles(layer, new HashSet<string>());
    }

    Directory.CreateDirectory(Path.Combine(root, "docs/refactoring"));
    var output = Path.Combine(root, "docs/refactoring/CODE_ORGANIZATION_INVENTORY.json");
    File.WriteAllText(output, JsonSerializer.Serialize(new { filesAnalyzed = files.Length, typesClassified = typeCount, entries, dependencies, violations }, new JsonSerializerOptions { WriteIndented = true }));
    Console.WriteLine($"Files: {files.Length}; types: {typeCount}; violations: {violations.Count}; inventory: {output}");
    foreach (var violation in violations) Console.WriteLine(violation);
    return violations.Count == 0 ? 0 : 1;

    void DetectCycles(string layer, HashSet<string> path)
    {
        if (!path.Add(layer))
        {
            violations.Add($"dependency-cycle: {string.Join(" -> ", path)} -> {layer}");
            return;
        }

        if (graph.TryGetValue(layer, out var targets))
        {
            foreach (var target in targets) DetectCycles(target, new HashSet<string>(path));
        }
    }
}
catch (Exception ex)
{
    Console.Error.WriteLine(ex.Message);
    return 2;
}

static string Name(SyntaxNode type) => type switch
{
    BaseTypeDeclarationSyntax declaration => declaration.Identifier.Text,
    DelegateDeclarationSyntax declaration => declaration.Identifier.Text,
    _ => throw new ArgumentException("Expected a type declaration.")
};
