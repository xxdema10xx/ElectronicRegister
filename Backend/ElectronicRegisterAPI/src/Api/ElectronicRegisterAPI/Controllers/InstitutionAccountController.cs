using ElectronicRegisterAPI.Api.Contracts;
using ElectronicRegisterAPI.Api.ExceptionHandling;
using ElectronicRegisterAPI.Api.Security;
using ElectronicRegisterAPI.Domain.Configuration;
using ElectronicRegisterAPI.Domain.Enums;
using ElectronicRegisterAPI.Domain.Interfaces.Managers;
using ElectronicRegisterAPI.Domain.Models;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace ElectronicRegisterAPI.Api.Controllers;

// Institution-scoped account creation (InstitutionAdmin any role; Staff Student/Teacher).
// Off unless Multitenancy:SchoolApi, Multitenancy:MembershipWriteApi and
// Multitenancy:PlatformIdentity are enabled (in Production they also require
// Deployment:RolloutApproved). The address is generated by the server.
[ApiController, Route("api/institution/accounts"), InstitutionSchoolEndpoint, RequestSizeLimit(16384), MembershipApiErrors]
public sealed class InstitutionAccountController(IInstitutionAccountManager manager) : ControllerBase
{
    [HttpPost, Authorize(Roles = "InstitutionAdmin,Staff")]
    [InstitutionPermission(InstitutionPermission.UserCreate)]
    public async Task<IActionResult> Create(
        CreateInstitutionAccountRequest request,
        [FromServices] IConfiguration configuration,
        [FromServices] PlatformIdentitySettings platform,
        CancellationToken ct
    )
    {
        if (!InstitutionMembershipWriteEndpointAttribute.Enabled(configuration) || !platform.Enabled)
            return NotFound();
        InstitutionAccountCreated result;
        try
        {
            result = await manager.CreateAsync(request.ToDomain(), ct);
        }
        catch (ArgumentException error) when (error.GetType() == typeof(ArgumentException))
        {
            // Curated validation messages only (InstitutionAccountRules, ToDomain): they never
            // contain request values, fiscal codes or data of another institution.
            return BadRequest(new ProblemDetails { Status = StatusCodes.Status400BadRequest, Title = "Richiesta non valida", Detail = error.Message });
        }
        // The temporary password is shown once: never cache this response anywhere.
        Response.Headers.CacheControl = "no-store";
        Response.Headers.Pragma = "no-cache";
        return result.Replayed ? Ok(result) : StatusCode(StatusCodes.Status201Created, result);
    }
}
