"""Production-like account flow on a running isolated staging (after host.py start).

Runs the 18-step owner/institution account flow with:
- the API image built from the commit under test, ASPNETCORE_ENVIRONMENT=Production,
  Deployment:Mode=Production and an explicit Deployment:RolloutApproved=true;
- MySQL 8.4.13 over TLS 1.2 with SslMode=VerifyFull, the CA generated by this staging's
  prepare step, non-root application and owner identities;
- HTTPS through infra/nginx.release.conf with a CA generated during this run.
Negative cases: wrong CA and disabled TLS towards MySQL are rejected, Production refuses
to start without RolloutApproved, the API publishes no HTTP port, plain HTTP on the proxy
only redirects, and no temporary password appears in API or proxy logs.

Nothing here is secret-bearing output: credentials stay in the root-only state folder and
are mounted read-only; only step outcomes are printed. All containers are removed at the end.
"""
import argparse
import http.client
import ipaddress
import json
import os
from pathlib import Path
import re
import ssl
import subprocess
import sys
import time
import uuid

sys.path.insert(0, str(Path(__file__).resolve().parent))
import host  # noqa: E402  (reuses ownership/state loading and safe file creation)

DOMAIN = 'api.example.test'
HTTPS_PORT, HTTP_PORT = 18443, 18480
NGINX_IMAGE = 'nginx:1.27-alpine'
require = host.require


class Flow:
    def __init__(self, folder, state, owner_tool=None):
        self.folder, self.s, self.owner_tool = folder, state, owner_tool
        self.work = folder / 'production'
        self.project = state['project']
        self.network = self.project + '_backend'
        self.image = self.project + '-api:' + state['revision']
        self.api, self.proxy, self.blocked = self.project + '-prod-api', self.project + '-prod-proxy', self.project + '-prod-norollout'
        self.results, self.secrets = [], []
        net = ipaddress.ip_network(state['subnet'])
        self.proxy_ip = str(net.network_address + 250)

    # ---- helpers -------------------------------------------------------------
    def step(self, name, ok, detail=''):
        self.results.append(dict(step=name, ok=bool(ok), detail=detail))
        print(('PASS ' if ok else 'FAIL ') + name + (' - ' + detail if detail else ''), flush=True)

    def docker(self, *args, check=True, timeout=600):
        p = subprocess.run(['docker', *map(str, args)], capture_output=True, text=True, timeout=timeout)
        if check and p.returncode:
            raise RuntimeError('docker ' + str(args[0]) + ' failed (exit ' + str(p.returncode) + ')')
        return p

    def openssl(self, *args):
        with (self.work / 'pki.log').open('a') as log:
            host.run(['openssl', *args], stdout=log, stderr=log)

    def https(self, method, path, token=None, body=None):
        context = ssl.create_default_context(cafile=str(self.work / 'https-ca.pem'))
        context.minimum_version = ssl.TLSVersion.TLSv1_2
        connection = http.client.HTTPSConnection('127.0.0.1', HTTPS_PORT, context=context, timeout=30)
        headers = {'Host': DOMAIN}
        data = None
        if body is not None:
            data = json.dumps(body).encode()
            headers['Content-Type'] = 'application/json'
        if token:
            headers['Authorization'] = 'Bearer ' + token
        try:
            connection.request(method, path, body=data, headers=headers)
            response = connection.getresponse()
            raw = response.read()
            try:
                payload = json.loads(raw) if raw else None
            except ValueError:
                payload = None
            return response.status, payload, {k.lower(): v for k, v in response.getheaders()}
        finally:
            connection.close()

    def tool(self, *args, connection='owner-connection'):
        p = self.docker('run', '--rm', '--network', self.network, '--user', '1654:1654', '--read-only',
                        '--tmpfs', '/tmp:uid=1654,gid=1654,mode=0700', '--cap-drop', 'ALL', '--security-opt', 'no-new-privileges:true',
                        '-e', 'HOME=/tmp', '-e', 'DOTNET_CLI_TELEMETRY_OPTOUT=1', '--label', 'io.er.staging.id=' + self.s['id'],
                        '-v', str(self.work / 'owner-tool') + ':/tool:ro',
                        '-v', str(self.work / connection) + ':/run/secrets/owner-connection:ro',
                        '-v', str(self.work / 'mysql-ca.pem') + ':/run/secrets/mysql-ca.pem:ro',
                        '-v', str(self.work / 'wrong-ca.pem') + ':/run/secrets/wrong-ca.pem:ro',
                        '--entrypoint', 'dotnet', self.image, '/tool/OwnerProvisioning.dll', *args,
                        '--connection-file', '/run/secrets/owner-connection', '--expected-server-uuid', self.uuid, check=False)
        lines = dict(line.split(': ', 1) for line in p.stdout.splitlines() if ': ' in line)
        password = next((v for k, v in lines.items() if k.startswith('temporary password (shown once')), None)
        if password:
            self.secrets.append(password)
        return p.returncode, lines, password

    def root_sql(self, statement):
        cid = host.compose(self.folder, 'ps', '-q', 'db', capture=True)
        return host.output(['docker', 'exec', cid, 'mysql', '--defaults-extra-file=/run/secrets/root.cnf', '--protocol=SOCKET',
                            '--batch', '--skip-column-names', 'electronic_register_staging', '-e', statement])

    def login(self, email, password):
        status, body, _ = self.https('POST', '/api/Auth/identity/login', body=dict(email=email, password=password))
        return status, body

    def access(self, ticket):
        status, choices, _ = self.https('GET', '/api/Auth/institutions', ticket)
        if status != 200 or len(choices) != 1:
            return None, status
        choice = choices[0]
        status, body, _ = self.https('POST', '/api/Auth/select-institution', ticket, dict(institutionId=choice['institutionId'], membershipId=choice['membershipId']))
        return (body['token'] if status == 200 else None), status

    def activate(self, email, temporary, final):
        status, ticket = self.login(email, temporary)
        ok = status == 200 and ticket['passwordChangeRequired'] is True
        before = self.https('GET', '/api/Auth/institutions', ticket['ticket'])[0] if ok else 0
        change = self.https('PUT', '/api/identity/account/password', ticket['ticket'], dict(currentPassword=temporary, newPassword=final))[0] if ok else 0
        old = self.https('GET', '/api/identity/account', ticket['ticket'])[0] if ok else 0
        self.secrets.append(final)
        status2, fresh = self.login(email, final)
        token, selected = self.access(fresh['ticket']) if status2 == 200 else (None, status2)
        detail = f'temp-login={status} before-change={before} change={change} old-ticket={old} new-login={status2} select={selected}'
        return ok and before == 401 and change == 204 and old == 401 and status2 == 200 and fresh['passwordChangeRequired'] is False and token is not None, token, detail

    # ---- setup ---------------------------------------------------------------
    def prepare(self):
        require(not self.work.exists(), 'Production flow already ran for this staging: prepare a NEW staging')
        self.work.mkdir(mode=0o700)
        labels = json.loads(host.output(['docker', 'network', 'inspect', '--format', '{{json .Labels}}', self.network]))
        require(labels.get('io.er.staging.id') == self.s['id'], 'Backend network not owned by this staging')
        # HTTPS PKI generated now, never stored outside the root-only state.
        self.openssl('req', '-x509', '-newkey', 'rsa:3072', '-sha256', '-nodes', '-keyout', self.work / 'https-ca-key.pem', '-out', self.work / 'https-ca.pem',
                     '-days', '2', '-subj', '/CN=er-production-flow-ca', '-addext', 'basicConstraints=critical,CA:TRUE', '-addext', 'keyUsage=critical,keyCertSign,cRLSign')
        self.openssl('req', '-new', '-newkey', 'rsa:3072', '-sha256', '-nodes', '-keyout', self.work / 'api-key.pem', '-out', self.work / 'api.csr', '-subj', '/CN=' + DOMAIN)
        host.write(self.work / 'api.ext', 'basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:' + DOMAIN + ',IP:127.0.0.1\n')
        self.openssl('x509', '-req', '-in', self.work / 'api.csr', '-CA', self.work / 'https-ca.pem', '-CAkey', self.work / 'https-ca-key.pem', '-CAcreateserial',
                     '-out', self.work / 'api-fullchain.pem', '-days', '2', '-sha256', '-extfile', self.work / 'api.ext')
        os.chmod(self.work / 'https-ca.pem', 0o444)
        # Production runtime: same reviewed staging runtime, release mode, explicit rollout approval.
        release = json.loads((host.ROOT / 'infra/release.runtime.example.json').read_text())
        runtime = host.runtime_configuration(DOMAIN, self.proxy_ip)
        runtime['Deployment'] = dict(Mode='Production', RolloutApproved=True)
        runtime['Transport'] = dict(KnownProxies=[self.proxy_ip], AllowedOrigins=['https://app.example.test'], HttpsPort=443)
        runtime['Multitenancy'] = release['Multitenancy']
        require(runtime['Multitenancy']['SchoolApi']['Enabled'] and runtime['Multitenancy']['MembershipWriteApi']['Enabled'], 'Release example no longer enables the account endpoint flags')
        host.write(self.work / 'runtime.json', json.dumps(runtime, indent=2), mode=0o444)
        host.write(self.work / 'runtime-without-rollout.json', json.dumps({**runtime, 'Deployment': dict(Mode='Production', RolloutApproved=False)}, indent=2), mode=0o444)
        # Owner identity: the non-root migrator, VerifyFull with the staging CA (never root).
        password = (self.folder / 'secrets/db/migrator-password').read_text().strip()
        base = 'Server=er-stage-db;Port=3306;Database=electronic_register_staging;User ID=er_migrator;Password=' + password + ';TlsVersion=TLS 1.2;'
        for name, mode in (('owner-connection', 'SslMode=VerifyFull;SslCa=/run/secrets/mysql-ca.pem'),
                           ('owner-connection-wrong-ca', 'SslMode=VerifyFull;SslCa=/run/secrets/wrong-ca.pem'),
                           ('owner-connection-no-tls', 'SslMode=None')):
            host.write(self.work / name, base + mode, 1654, 1654, 0o400)
        host.write(self.work / 'mysql-ca.pem', (self.folder / 'pki/ca.pem').read_text(), 1654, 1654, 0o444)
        host.write(self.work / 'wrong-ca.pem', (self.folder / 'pki/wrong-ca.pem').read_text(), 1654, 1654, 0o444)
        # Owner tool is built here and mounted for the run only: it is never part of the API image.
        if self.owner_tool:
            # Published by the caller without root (CI: setup-dotnet is not on sudo's PATH).
            require((Path(self.owner_tool) / 'OwnerProvisioning.dll').is_file(), 'Published owner tool missing')
            import shutil
            shutil.copytree(self.owner_tool, self.work / 'owner-tool')
        else:
            host.run(['dotnet', 'publish', host.ROOT / 'tools/OwnerProvisioning/OwnerProvisioning.csproj', '-c', 'Release', '-o', self.work / 'owner-tool',
                      '--nologo', '-v', 'quiet', '/p:UseAppHost=false'], stdout=subprocess.DEVNULL)
        variables = self.root_sql("SHOW GLOBAL VARIABLES LIKE 'server_uuid'")
        self.uuid = variables.split('\t')[-1]
        require(re.fullmatch(r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}', self.uuid), 'Unexpected server UUID')

    def api_container(self, name, runtime):
        return ['run', '-d', '--name', name, '--network', self.network, '--network-alias', 'er-api' if name == self.api else name,
                '--user', '1654:1654', '--read-only', '--tmpfs', '/tmp:uid=1654,gid=1654,mode=0700', '--cap-drop', 'ALL',
                '--security-opt', 'no-new-privileges:true', '--label', 'io.er.staging.id=' + self.s['id'],
                '-e', 'ASPNETCORE_ENVIRONMENT=Production', '-e', 'ER_RUNTIME_CONFIG=/run/config/runtime.json',
                '-v', str(self.work / runtime) + ':/run/config/runtime.json:ro',
                '-v', str(self.folder / 'secrets/api/connection') + ':/run/secrets/ConnectionStrings__DefaultConnection:ro',
                '-v', str(self.folder / 'secrets/api/jwt-key') + ':/run/secrets/Jwt__Key:ro',
                '-v', str(self.folder / 'secrets/api/ca.pem') + ':/run/secrets/mysql-ca.pem:ro', self.image]

    def start(self):
        # Production without explicit rollout approval must refuse to start.
        self.docker(*self.api_container(self.blocked, 'runtime-without-rollout.json'))
        try:
            code = self.docker('wait', self.blocked, timeout=120).stdout.strip()
        except subprocess.TimeoutExpired:
            code = 'still-running-after-120s'
        logs = self.docker('logs', self.blocked, check=False)
        refused = 'Runtime security configuration is incomplete or unsafe.' in logs.stdout + logs.stderr
        self.step('Production refuses to start without Deployment:RolloutApproved=true (RuntimePolicy)', code not in ('', '0') and refused, 'exit=' + code + ' policy-message=' + str(refused))
        self.docker('rm', '-f', self.blocked, check=False)
        self.docker(*self.api_container(self.api, 'runtime.json'))
        self.docker('pull', '-q', NGINX_IMAGE)
        digest = self.docker('image', 'inspect', '--format', '{{index .RepoDigests 0}}', NGINX_IMAGE).stdout.strip()
        conf = (host.ROOT / 'infra/nginx.release.conf').read_text()
        require('server_name ' + DOMAIN in conf and 'proxy_pass http://er-api:8080;' in conf, 'infra/nginx.release.conf changed: review the flow')
        host.write(self.work / 'nginx.conf', conf, mode=0o444)
        os.chmod(self.work / 'api-key.pem', 0o400)
        self.docker('run', '-d', '--name', self.proxy, '--network', self.network, '--ip', self.proxy_ip,
                    '-p', f'127.0.0.1:{HTTPS_PORT}:443', '-p', f'127.0.0.1:{HTTP_PORT}:80', '--label', 'io.er.staging.id=' + self.s['id'],
                    '--read-only', '--tmpfs', '/var/cache/nginx', '--tmpfs', '/var/run', '--tmpfs', '/tmp',
                    '-v', str(self.work / 'nginx.conf') + ':/etc/nginx/conf.d/default.conf:ro',
                    '-v', str(self.work / 'api-fullchain.pem') + ':/run/secrets/api-fullchain.pem:ro',
                    '-v', str(self.work / 'api-key.pem') + ':/run/secrets/api-key.pem:ro', digest)
        ready = 0
        for _ in range(60):
            try:
                ready = self.https('GET', '/health/ready')[0]
                if ready == 200:
                    break
            except (OSError, ssl.SSLError, http.client.HTTPException):
                pass
            time.sleep(2)
        self.step('API ready over HTTPS through infra/nginx.release.conf (proxy image ' + digest.split('@')[-1][:19] + ')', ready == 200, 'status=' + str(ready))
        runtime = json.loads(self.docker('exec', self.api, 'cat', '/run/config/runtime.json').stdout)
        self.step('runtime is Production with explicit RolloutApproved=true', runtime['Deployment'] == dict(Mode='Production', RolloutApproved=True))
        bindings = json.loads(self.docker('inspect', '--format', '{{json .HostConfig.PortBindings}}', self.api).stdout) or {}
        self.step('API publishes no HTTP port on the host', not bindings, json.dumps(bindings))
        connection = http.client.HTTPConnection('127.0.0.1', HTTP_PORT, timeout=10)
        try:
            connection.request('GET', '/health/ready', headers={'Host': DOMAIN})
            response = connection.getresponse()
            location = response.getheader('Location') or ''
            response.read()
        finally:
            connection.close()
        self.step('plain HTTP on the proxy only redirects to HTTPS', response.status == 308 and location.startswith('https://' + DOMAIN), f'status={response.status}')

    # ---- flow ----------------------------------------------------------------
    def run_flow(self):
        suffix = uuid.uuid4().hex[:10]
        code_prefix = 'PF_' + suffix
        admin = f'admin.{suffix}@scuola.example.test'
        code, _, _ = self.tool('create-institution', '--code', code_prefix + '_X', '--name', 'Rifiutato', '--admin-email', 'x.' + admin, connection='owner-connection-wrong-ca')
        code2, _, _ = self.tool('create-institution', '--code', code_prefix + '_Y', '--name', 'Rifiutato', '--admin-email', 'y.' + admin, connection='owner-connection-no-tls')
        rows = self.root_sql(f"SELECT COUNT(*) FROM institution WHERE code IN ('{code_prefix}_X','{code_prefix}_Y')")
        self.step('MySQL rejects the wrong CA and disabled TLS (owner script), nothing written', code != 0 and code2 != 0 and rows == '0', f'wrong-ca-exit={code} no-tls-exit={code2} rows={rows}')
        code, out, temporary = self.tool('create-institution', '--code', code_prefix, '--name', 'Istituto prova produzione', '--admin-email', admin)
        self.step('owner script over VerifyFull: create institution + first admin', code == 0 and temporary is not None, f"exit={code} status={out.get('status')}")
        code, out2, again = self.tool('create-institution', '--code', code_prefix, '--name', 'Istituto prova produzione', '--admin-email', admin)
        self.step('owner script: idempotent, password not shown again', code == 0 and again is None and out2.get('status') == 'already-provisioned')
        ok, admin_access, detail = self.activate(admin, temporary, 'AdminProduction!1')
        self.step('admin: temporary password, forced change, select institution', ok, detail)
        status, context, _ = self.https('GET', '/api/Auth/context', admin_access)
        self.step('admin: access token scoped to the institution as InstitutionAdmin', status == 200 and context['roles'] == ['InstitutionAdmin'] and context['institutionId'] == out.get('institution'))
        status = self.https('POST', '/api/identity/accounts', None, dict(email=f'free.{suffix}@x.example.test', password='Registered!1'))[0]
        self.step('public registration POST /api/identity/accounts is gone', status == 404, f'status={status}')
        teacher = f'docente.{suffix}@scuola.example.test'
        body = dict(eventId=str(uuid.uuid4()), email=teacher, roles=['Teacher'], firstName='Luca', lastName='Verdi', reason='Prova produzione')
        status, created, headers = self.https('POST', '/api/institution/accounts', admin_access, body)
        teacher_temp = (created or {}).get('temporaryPassword') if status == 201 else None
        if teacher_temp:
            self.secrets.append(teacher_temp)
        self.step('admin creates a teacher account (new profile)', status == 201 and teacher_temp and created.get('teacherId') and headers.get('cache-control') == 'no-store', f"status={status} cache={headers.get('cache-control')}")
        status, replay, _ = self.https('POST', '/api/institution/accounts', admin_access, body)
        self.step('replay of the same eventId returns ids without the password', status == 200 and replay.get('replayed') is True and replay.get('temporaryPassword') is None and replay.get('userId') == (created or {}).get('userId'))
        status, conflict, _ = self.https('POST', '/api/institution/accounts', admin_access, {**body, 'eventId': str(uuid.uuid4())})
        self.step('same email again: single neutral 409', status == 409 and (conflict or {}).get('title') == 'Indirizzo email non disponibile', f'status={status}')
        ok, teacher_access, detail = self.activate(teacher, teacher_temp, 'TeacherProduction!1')
        self.step('teacher: temporary password, forced change, select institution', ok, detail)
        status, context, _ = self.https('GET', '/api/Auth/context', teacher_access)
        me = self.https('GET', '/api/institution/teachers/me', teacher_access)[0]
        self.step('teacher: roles exactly [Teacher], linked profile readable', status == 200 and context['roles'] == ['Teacher'] and me == 200, f'context={status} me={me}')
        status = self.https('POST', '/api/institution/accounts', teacher_access, {**body, 'eventId': str(uuid.uuid4()), 'email': f'x.{suffix}@x.example.test'})[0]
        self.step('teacher cannot create accounts', status == 403, f'status={status}')
        code, _, reset = self.tool('reset-password', '--email', teacher)
        self.step('owner script: reset teacher password', code == 0 and reset is not None, f'exit={code}')
        old_token = self.https('GET', '/api/Auth/context', teacher_access)[0]
        old_password = self.login(teacher, 'TeacherProduction!1')[0]
        status, ticket = self.login(teacher, reset)
        self.step('after reset: old token and password rejected, temporary login forces change', old_token == 401 and old_password == 401 and status == 200 and ticket['passwordChangeRequired'] is True,
                  f'old-token={old_token} old-password={old_password} temp-login={status}')
        ok, _, detail = self.activate(teacher, reset, 'TeacherProduction!2')
        self.step('teacher: reactivated after reset', ok, detail)
        self.step('other accounts untouched by the teacher reset', self.https('GET', '/api/Auth/context', admin_access)[0] == 200)
        code, _, _ = self.tool('reset-password', '--email', admin)
        status = self.https('GET', '/api/Auth/context', admin_access)[0]
        self.step('owner script: reset admin revokes its token', code == 0 and status == 401, f'exit={code} old-token={status}')

    def logs(self):
        text = self.docker('logs', self.api, check=False)
        proxy = self.docker('logs', self.proxy, check=False)
        combined = text.stdout + text.stderr + proxy.stdout + proxy.stderr
        leaks = sum(1 for secret in self.secrets if secret and secret in combined)
        self.step('no temporary or chosen password in API or proxy logs', leaks == 0 and len(self.secrets) >= 6, f'passwords checked={len(self.secrets)} found={leaks} log-lines={combined.count(chr(10))}')

    def cleanup(self):
        for name in (self.api, self.proxy, self.blocked):
            self.docker('rm', '-f', '-v', name, check=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--state', required=True)
    parser.add_argument('--owner-tool', help='Directory with a published tools/OwnerProvisioning build')
    args = parser.parse_args()
    require(sys.platform.startswith('linux') and os.geteuid() == 0, 'Run as root on the staging Linux host')
    folder, state = host.load(args.state)
    host.owned(state)
    host.check_images(folder, state)
    flow = Flow(folder, state, args.owner_tool)
    try:
        flow.prepare()
        flow.start()
        flow.run_flow()
        flow.logs()
    finally:
        flow.cleanup()
    (flow.work / 'production-flow.json').write_text(json.dumps(dict(revision=state['revision'], results=flow.results), indent=2) + '\n')
    passed = sum(r['ok'] for r in flow.results)
    print(json.dumps(dict(productionFlow=dict(PASS=passed, FAIL=len(flow.results) - passed), revision=state['revision'])))
    sys.exit(0 if passed == len(flow.results) else 1)


if __name__ == '__main__':
    try:
        main()
    except (RuntimeError, subprocess.CalledProcessError, subprocess.TimeoutExpired, OSError, KeyError, TypeError) as error:
        print('Production flow failed: ' + type(error).__name__ + ': ' + str(error), file=sys.stderr)
        sys.exit(1)
